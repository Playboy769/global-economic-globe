def qid(subject, head, opts):
    """內容雜湊當題目 ID：重新產生考卷、換 seed 都不會變，錯題紀錄才對得起來。"""
    norm = re.sub(r'\s+', '', subject + '|' + head + '|' +
                  '|'.join(L + b for L, b in opts))
    return hashlib.sha1(norm.encode('utf-8')).hexdigest()[:12]


def tag(subject, text):
    for lab, pat in COMP.get(subject, []):
        if pat.search(text):
            return lab
    return '其他'


# ---------------------------------------------------------------- 組卷
SUBJECTS = ['投資學', '財務分析', '法規']


def build_real(recs, exam='115-2'):
    """115-2 真題：依原題號排序，只收可作答（A–D 選項齊全且有單一答案）者。"""
    out = {}
    for s in SUBJECTS:
        qs = [q for q in recs
              if q['exam'] == exam and q['subject'] == s
              and q['opts'] and len(q['opts']) == 4
              and q['ans'] and len(q['ans']) == 1 and q['ans'] in 'ABCD']
        qs.sort(key=lambda q: q['qno'])
        out[s] = [{
            'id': qid(s, q['head'], q['opts']),
            'head': q['head'], 'opts': q['opts'], 'ans': q['ans'],
            'tag': tag(s, q['raw']),
            'srcTxt': f"{exam.replace('-', '年第')}次 第{q['qno']}題（本屆原題）",
        } for q in qs]
    return out


def build_notes():
    """筆記練習：讀 s11_notes_import.py 的輸出，依科目合併成大池（不分期別）。"""
    path = os.path.join(OUT, 'notes_corpus.json')
    if not os.path.exists(path):
        return None
    recs = json.load(open(path, encoding='utf-8'))
    out = {}
    for s in SUBJECTS:
        qs = [q for q in recs if q['subject'] == s]
        out[s] = [{
            'id': qid(s, q['head'], q['opts']),
            'head': q['head'], 'opts': q['opts'], 'ans': q['ans'],
            'tag': tag(s, q['head'] + ' ' + ' '.join(b for _, b in q['opts'])),
            'srcTxt': q['srcTxt'],
            'ex': q['explain'],
        } for q in qs]
    return out


def build_mock():
    """115-3 模擬：直接呼叫 s6_mockexam 的抽樣，攔截結果不覆寫既有 HTML。"""
    import s6_mockexam as s6
    cap = {}

    def grab(paper, stats):
        cap['paper'], cap['stats'] = paper, stats

    orig, s6.write_html = s6.write_html, grab
    try:
        s6.main()
    finally:
        s6.write_html = orig

    out = {}
    for s in SUBJECTS:
        picked = cap['paper'][s]
        out[s] = [{
            'id': qid(s, c['head'], c['opts']),
            'head': c['head'], 'opts': c['opts'], 'ans': c['ans'],
            'tag': tag(s, c['head'] + ' ' + ' '.join(b for _, b in c['opts'])),
            'srcTxt': (f"曾出現 {c['k']} 次：{'、'.join(c['exams'])}"
                       f"　｜　本卷採用 {c['from']} 版本"
                       + ("　｜　⚠ 選項曾被改寫" if c['variants'] > 1 else "")),
        } for c in picked]
    return out, cap['stats']


